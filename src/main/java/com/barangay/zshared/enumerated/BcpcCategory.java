package com.barangay.zshared.enumerated;

/**
 * Defines the primary category of a child under the Barangay Council for the Protection of Children (BCPC),
 * compliant with Republic Act 9344 (Juvenile Justice and Welfare Act of 2006) as amended by RA 10630.
 */
public enum BcpcCategory {
    /**
     * Child at Risk (CAR): A child who is vulnerable to and at the risk of committing criminal offenses
     * or being abused/exploited due to personal, family, or social circumstances.
     */
    CAR,

    /**
     * Child in Conflict with the Law (CICL): A child who is alleged as, accused of, or adjudged as having
     * committed an offense under Philippine laws.
     */
    CICL
}

